"""Generate stand-alone Python (matplotlib) and MATLAB scripts that redraw a scene's 3-D and 2-D figures.

The geometry is embedded as plain numbers (conic parameters rather than sampled points, so the code stays readable and editable); every label is
LaTeX (matplotlib mathtext in Python, the latex interpreter in MATLAB). Scripts are theme-aware and need nothing but numpy + matplotlib / MATLAB.
"""
from __future__ import annotations
