def conic_points(o, n=721):
    p, e, Q = o['p'], o['e'], np.array(o['Q'])
    if o['ths'] is not None:
        a, b = o['ths']; b = b + 360 if b < a else b; th = np.radians(np.linspace(a, b, n))
    elif e < 1:
        th = np.radians(np.linspace(-180, 180, n))
    else:
        lim = np.degrees(np.arccos(-1 / e)) - 0.5 if e > 1 else 175.0
        if o['rmax']:
            c = (p / o['rmax'] - 1) / e
            if abs(c) < 1: lim = min(lim, np.degrees(np.arccos(c)))
        th = np.radians(np.linspace(-lim, lim, n))
    r = p / (1 + e * np.cos(th))
    return (Q @ np.vstack([r * np.cos(th), r * np.sin(th), np.zeros_like(th)])).T


