from .latex import tex, prose_escape_latex


def _f(x) -> str:
    return format(float(x), '.10g')


def _py(a) -> str:
    a = np.asarray(a, float)
    return _f(a) if a.ndim == 0 else '[' + ', '.join(_py(x) for x in a) + ']'


def _mat(a) -> str:
    a = np.asarray(a, float)
    if a.ndim == 0: return _f(a)
    if a.ndim == 1: return '[' + ' '.join(_f(x) for x in a) + ']'
    return '[' + '; '.join(' '.join(_f(x) for x in r) for r in a) + ']'


def safe_name(s: str, prefix: str = 'plot') -> str:
    """A valid MATLAB / Python identifier for the file name."""
    s = re.sub(r'\W+', '_', s).strip('_') or prefix
    return s if re.match(r'[A-Za-z]', s) else prefix + '_' + s


def scene_data(sc: Scene, theme: str, body: str) -> dict:
    T = THEMES[theme]; col = lambda r: color(theme, r); L = lambda s: tex(s, body) if s else ''
    planes = []
    for pl in sc.planes:
        s = pl.size; n = unit(pl.normal); a = np.array([1.0, 0, 0]) if abs(n[0]) < 0.9 else np.array([0, 1.0, 0]); e1 = unit(np.cross(n, a)); e2 = np.cross(n, e1)
        planes.append(dict(label=L(pl.label), corners=[pl.center + s * (sx * e1 + sy * e2) for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))], color=col(pl.role)))
    arcs = []
    for a in sc.arcs:
        pts, ang = a.points()
        if ang: arcs.append(dict(label=L(a.label), pts=pts[::2], color=col(a.role), only3d=a.only3d))
    return dict(
        theme=dict(bg=T['surface'], ink=T['ink'], ink2=T['ink2'], grid=T['grid']),
        orbits=[dict(name=L(o.name), p=o.p, e=o.e, Q=o.Q, ths=o.ths_range, rmax=o.rmax, dash=o.dash, color=col(o.role)) for o in sc.orbits],
        vecs=[dict(label=L(v.label), origin=v.origin, vec=v.vec, scale=v.scale, color=col(v.role), dash=v.dash) for v in sc.vecs],
        pts=[dict(label=L(p.label), pos=p.pos, color=(T['ink'] if p.role == 'ink' else col(p.role)), marker=p.marker) for p in sc.pts],
        lines=[dict(label=L(l.label), p0=l.p0, p1=l.p1, color=col(l.role), dash=l.dash) for l in sc.lines],
        polys=[dict(label=L(p.label), pts=p.pts, color=col(p.role), dash=p.dash) for p in sc.polys],
        disks=[dict(center=d.center, radius=d.radius, color=T['body']) for d in sc.disks],
        triads=[dict(origin=t.origin, axes=t.axes, names=[L(n) for n in t.names], length=t.length, color=col(t.role), only3d=t.only3d) for t in sc.triads],
        planes=planes, arcs=arcs, e1=sc.plane2d[0], e2=sc.plane2d[1], units=sc.units)


