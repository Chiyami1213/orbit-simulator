def _lit(items: list[str]) -> str:
    return ''.join('\n    ' + it + ',' for it in items)


def python_script(sc: Scene, title: str, theme: str = 'light', body: str = 'symbol', inputs: dict | None = None, filename: str = 'plot.py') -> str:
    D = scene_data(sc, theme, body); r = repr
    orbits = [f"dict(name={r(o['name'])}, p={_f(o['p'])}, e={_f(o['e'])}, Q={_py(o['Q'])}, ths={_py(o['ths']) if o['ths'] else 'None'}, rmax={_f(o['rmax']) if o['rmax'] else 'None'}, dash={o['dash']}, color={r(o['color'])})" for o in D['orbits']]
    vecs = [f"dict(label={r(v['label'])}, origin={_py(v['origin'])}, vec={_py(v['vec'])}, scale={_f(v['scale'])}, color={r(v['color'])})" for v in D['vecs']]
    pts = [f"dict(label={r(p['label'])}, pos={_py(p['pos'])}, color={r(p['color'])})" for p in D['pts']]
    lines = [f"dict(label={r(l['label'])}, p0={_py(l['p0'])}, p1={_py(l['p1'])}, dash={l['dash']}, color={r(l['color'])})" for l in D['lines']]
    polys = [f"dict(label={r(p['label'])}, pts={_py(p['pts'][::4])}, dash={p['dash']}, color={r(p['color'])})" for p in D['polys']]
    arcs = [f"dict(label={r(a['label'])}, pts={_py(a['pts'])}, only3d={a['only3d']}, color={r(a['color'])})" for a in D['arcs']]
    disks = [f"dict(center={_py(d['center'])}, radius={_f(d['radius'])}, color={r(d['color'])})" for d in D['disks']]
    tri = [f"dict(origin={_py(t['origin'])}, axes={_py(t['axes'])}, names={t['names']!r}, length={_f(t['length'])}, only3d={t['only3d']}, color={r(t['color'])})" for t in D['triads']]
    pls = [f"dict(label={r(p['label'])}, corners={_py(p['corners'])}, color={r(p['color'])})" for p in D['planes']]
    T = D['theme']; plain = re.sub(r'\$', '', title)
    inp = ('Inputs: ' + '; '.join(f'{k} = {v}' for k, v in (inputs or {}).items() if not isinstance(v, (dict, list)))) if inputs else ''
    s = PY
    for k, v in {'TITLE_PLAIN': plain, 'FILE': filename, 'INPUTS': inp + ('\n' if inp else ''), 'TITLE': r(tex(title, body)), 'UNITS': r(D['units']), 'COLORS': f"{r(T['bg'])}, {r(T['ink'])}, {r(T['ink2'])}, {r(T['grid'])}",
                 'ORBITS': _lit(orbits), 'VECTORS': _lit(vecs), 'POINTS': _lit(pts), 'LINES': _lit(lines), 'POLYS': _lit(polys), 'ARCS': _lit(arcs), 'DISKS': _lit(disks),
                 'TRIADS': _lit(tri), 'PLANES': _lit(pls), 'E1': _py(D['e1']), 'E2': _py(D['e2'])}.items():
        s = s.replace('@@' + k + '@@', v)
    return s


# ----------------------------------------------------------------------------------------------------------------------------------- MATLAB
def ml(s: str) -> str:
    """A LaTeX label as a MATLAB string literal for the latex interpreter: prose escaped, $...$ maths untouched, quotes doubled."""
    parts = re.split(r'(\$[^$]*\$)', s); out = ''.join(p if p.startswith('$') and p.endswith('$') and len(p) > 1 else prose_escape_latex(p) for p in parts)
    return "'" + out.replace("'", "''") + "'"


