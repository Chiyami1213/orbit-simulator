"""Generate mathkit/ui/web/icons.js from the Lucide icon set (ISC licence, https://lucide.dev; see LICENSES/lucide-ISC.txt).

Downloads the listed icons from the lucide-static package on jsDelivr and writes their inner SVG markup (24x24, stroke based) as an ICO map that replaces the hand-drawn icons.
Run once when the icon list changes:  python packaging/make_icons.py
"""
import pathlib
import re
import urllib.request

VERSION = '0.468.0'
BASE = f'https://cdn.jsdelivr.net/npm/lucide-static@{VERSION}/icons/'
# our icon name -> Lucide icon name
MAP = {
    'cal': 'calendar', 'orbit': 'orbit', 'check': 'circle-check-big', 'gear': 'settings', 'left': 'chevrons-left', 'right': 'chevrons-right', 'grid': 'layout-grid',
    'tools': 'sliders-horizontal', 'down': 'chevron-down', 'rc': 'chevron-right', 'sun': 'sun', 'moon': 'moon', 'monitor': 'monitor',
    'nbody': 'atom', 'twobody': 'link-2', 'conic': 'orbit', 'kepler': 'timer', 'hyper': 'move-up-right', 'cube': 'box', 'zap': 'zap', 'hohmann': 'repeat', 'layers': 'layers',
    'globe': 'globe', 'assist': 'rocket', 'lambert': 'route', 'trash': 'trash-2', 'check2': 'check',
    'play': 'play', 'pause': 'pause', 'addc': 'circle-plus', 'eye': 'eye', 'orb2': 'circle-dot', 'palette': 'palette', 'dots': 'ellipsis', 'bolt': 'zap', 'info': 'info',
    'search': 'search', 'camera': 'camera', 'close': 'x', 'undo': 'undo-2', 'redo': 'redo-2', 'rev': 'rewind',
    'basic': 'bookmark', 'motion': 'move-right', 'orbitt': 'orbit', 'forces': 'asterisk', 'actions': 'zap',
    'rocks': 'gem', 'sat': 'satellite', 'whatif': 'circle-help', 'star': 'star', 'scene': 'sparkles',
    'menu': 'menu', 'newf': 'file-plus', 'openf': 'folder-open', 'guide': 'graduation-cap', 'savef': 'save', 'exit': 'log-out', 'news': 'megaphone', 'credits': 'scroll-text',
    'feedback': 'message-square', 'perf': 'gauge', 'debug': 'wrench', 'keys': 'keyboard', 'share': 'share-2',
}


def inner(svg: str) -> str:
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S).strip()
    body = re.sub(r'^<svg[^>]*>', '', svg, flags=re.S); body = re.sub(r'</svg>\s*$', '', body)
    return ' '.join(body.split())


def main():
    out = pathlib.Path(__file__).resolve().parents[1] / 'mathkit' / 'ui' / 'web' / 'icons.js'; cache = {}; lines = []
    for ours, theirs in MAP.items():
        if theirs not in cache:
            with urllib.request.urlopen(BASE + theirs + '.svg', timeout=30) as r: cache[theirs] = inner(r.read().decode('utf-8'))
        lines.append(f"  {ours}: '{cache[theirs].replace(chr(39), chr(34))}'")
    out.write_text('/* Icons: Lucide ' + VERSION + ' (ISC licence, https://lucide.dev). Generated by packaging/make_icons.py; replaces the hand-drawn set. */\nObject.assign(ICO, {\n' + ',\n'.join(lines) + '\n});\n', encoding='utf-8')
    print('wrote', out, len(MAP), 'icons from', len(cache), 'lucide files')


if __name__ == '__main__':
    main()
